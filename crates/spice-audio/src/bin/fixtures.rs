//! Emit the golden byte vectors shared by the Rust and TypeScript codecs.
//!
//! ```text
//! spice-audio-fixtures --output web/lab/tests/fixtures/spice-audio.json
//! ```
//!
//! Both implementations parse and re-encode the same bytes, which is what
//! keeps the browser client from drifting away from this crate the way the
//! two usbredir codecs drifted apart.

use std::path::PathBuf;
use std::process::ExitCode;

use serde_json::{Value, json};
use spice_audio::link::{LinkHeader, LinkMess, LinkReply, cap_word};
use spice_audio::message::{AudioData, MainInit, Message, ModeMessage, PlaybackStart, RecordStart};
use spice_audio::protocol::{self, AudioMode, ChannelType};
use spice_audio::server::{FAKE_CHANNELS, FAKE_CONNECTION_ID, FAKE_FREQUENCY, tone_frame};

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

/// A deterministic stand-in for the server's RSA key, so the fixture is stable.
///
/// The ticket step is not fixtured: RSA-OAEP is randomized, so the TypeScript
/// side is tested against a decrypting server, not against a golden blob.
fn placeholder_pub_key() -> Vec<u8> {
    (0..protocol::TICKET_PUBKEY_BYTES)
        .map(|index| u8::try_from(index % 251).unwrap())
        .collect()
}

fn framed(messages: &[Message]) -> Vec<u8> {
    messages.iter().flat_map(Message::encode).collect()
}

fn fixtures() -> Value {
    let main_mess = LinkMess::client(ChannelType::Main, 0, false);
    let playback_mess = LinkMess::client(ChannelType::Playback, FAKE_CONNECTION_ID, true);
    let record_mess = LinkMess::client(ChannelType::Record, FAKE_CONNECTION_ID, false);
    let reply = LinkReply {
        error: protocol::LINK_ERR_OK,
        pub_key: placeholder_pub_key(),
        common_caps: vec![
            cap_word(protocol::COMMON_CAP_PROTOCOL_AUTH_SELECTION)
                | cap_word(protocol::COMMON_CAP_AUTH_SPICE)
                | cap_word(protocol::COMMON_CAP_MINI_HEADER),
        ],
        channel_caps: vec![cap_word(protocol::PLAYBACK_CAP_OPUS)],
    };
    let init = MainInit {
        connection_id: FAKE_CONNECTION_ID,
        multi_media_time: 0,
    };
    let playback_start = PlaybackStart {
        channels: FAKE_CHANNELS,
        format: protocol::AUDIO_FMT_S16,
        frequency: FAKE_FREQUENCY,
        time: 0,
    };
    let record_start = RecordStart {
        channels: FAKE_CHANNELS,
        format: protocol::AUDIO_FMT_S16,
        frequency: FAKE_FREQUENCY,
    };
    let mode = ModeMessage {
        time: 0,
        mode: AudioMode::Raw,
        data: Vec::new(),
    };
    let data = AudioData {
        time: 10,
        samples: tone_frame(0),
    };
    let stream = framed(&[
        Message {
            kind: protocol::MSG_PLAYBACK_MODE,
            payload: mode.encode(),
        },
        Message {
            kind: protocol::MSG_PLAYBACK_START,
            payload: playback_start.encode(),
        },
        Message {
            kind: protocol::MSG_PLAYBACK_DATA,
            payload: data.encode(),
        },
        Message {
            kind: protocol::MSG_PLAYBACK_STOP,
            payload: Vec::new(),
        },
    ]);
    // A header whose declared payload exceeds the codec's bound. Both sides
    // must reject it rather than buffer toward it.
    let mut oversized = protocol::MSG_PLAYBACK_DATA.to_le_bytes().to_vec();
    oversized.extend_from_slice(
        &u32::try_from(protocol::MAX_MESSAGE_BYTES + 1)
            .unwrap()
            .to_le_bytes(),
    );

    json!({
        "comment": "Generated by spice-audio-fixtures; do not edit by hand.",
        "constants": {
            "magic": protocol::MAGIC,
            "version_major": protocol::VERSION_MAJOR,
            "version_minor": protocol::VERSION_MINOR,
            "connection_id": FAKE_CONNECTION_ID,
            "max_message_bytes": protocol::MAX_MESSAGE_BYTES,
            "max_link_bytes": protocol::MAX_LINK_BYTES,
        },
        "link": {
            "header_for_main": hex(&LinkHeader::encode(u32::try_from(main_mess.encode().len()).unwrap())),
            "mess_main": hex(&main_mess.encode()),
            "mess_playback_opus": hex(&playback_mess.encode()),
            "mess_record": hex(&record_mess.encode()),
            "reply": hex(&reply.encode()),
            "reply_header": hex(&LinkHeader::encode(u32::try_from(reply.encode().len()).unwrap())),
        },
        "messages": {
            "main_init": hex(&init.encode()),
            "playback_mode_raw": hex(&mode.encode()),
            "playback_start": hex(&playback_start.encode()),
            "playback_data": hex(&data.encode()),
            "record_start": hex(&record_start.encode()),
            "tone_frame_0": hex(&tone_frame(0)),
        },
        "framing": {
            "playback_stream": hex(&stream),
            "playback_stream_kinds": [
                protocol::MSG_PLAYBACK_MODE,
                protocol::MSG_PLAYBACK_START,
                protocol::MSG_PLAYBACK_DATA,
                protocol::MSG_PLAYBACK_STOP,
            ],
            "oversized_header": hex(&oversized),
        },
    })
}

fn main() -> ExitCode {
    let mut output: Option<PathBuf> = None;
    let mut args = std::env::args().skip(1);
    while let Some(argument) = args.next() {
        match argument.as_str() {
            "--output" => match args.next() {
                Some(value) => output = Some(PathBuf::from(value)),
                None => {
                    eprintln!("spice-audio-fixtures: --output needs a path");
                    return ExitCode::from(2);
                }
            },
            other => {
                eprintln!("spice-audio-fixtures: unknown argument {other}");
                return ExitCode::from(2);
            }
        }
    }
    let text = format!("{:#}\n", fixtures());
    match output {
        Some(path) => {
            if let Err(error) = std::fs::write(&path, text) {
                eprintln!("spice-audio-fixtures: {}: {error}", path.display());
                return ExitCode::FAILURE;
            }
        }
        None => print!("{text}"),
    }
    ExitCode::SUCCESS
}
